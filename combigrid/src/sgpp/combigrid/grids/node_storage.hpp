/**
 * @file node_storage.hpp
 * @brief Shared storage of the 1D node lists of sparse grids.
 */
#pragma once

#include <cstddef>
#include <functional>
#include <future>
#include <memory>
#include <mutex>
#include <sgpp/base/datatypes/DataVector.hpp>
#include <sgpp/combigrid/grids/node_row_key.hpp>
#include <span>
#include <unordered_map>
#include <vector>

namespace sgpp {
namespace combigrid {

/**
 * @brief Shared storage of the 1D node lists ("rows", see @c NodeRowKey) of sparse grids.
 *
 * Every sparse grid takes its node lists from the storage of its setup
 * (@c SparseGridSetup::getNodeStorage; by default the process-wide @ref global storage), so grids
 * with the same nodes share them: a row is generated once, on its first request, and lives as
 * long as some grid (or other holder of the returned pointer) uses it; the storage itself only
 * keeps a weak reference. Rows never change and never move.
 *
 * All methods are thread-safe. Concurrent requests of a row that is being generated wait for it;
 * the rows a request has to generate are generated in parallel (OpenMP) if they are large.
 */
class NodeStorage {
 public:
  /// Pointer to a row: the nodes with the boundary nodes (see @c NodeRowKey).
  using RowPtr = std::shared_ptr<const base::DataVector>;

  /// @brief Constructs an empty storage.
  NodeStorage();

  ~NodeStorage();

  NodeStorage(const NodeStorage&) = delete;
  NodeStorage& operator=(const NodeStorage&) = delete;

  /// @brief Returns the process-wide storage, the default of every @c SparseGridSetup.
  static const std::shared_ptr<NodeStorage>& global();

  /// @brief Returns the row of @p key (see @ref getRows).
  RowPtr getRow(const NodeRowKey& key);

  /**
   * @brief Returns the rows of @p keys (in their order), generating the missing ones.
   * @throws The exceptions of the node families (e.g. delta nodes of non-nested nodes).
   */
  std::vector<RowPtr> getRows(std::span<const NodeRowKey> keys);

  /// @brief Returns the number of rows in use.
  size_t nRows() const;

  /// @brief Returns the number of nodes of the rows in use.
  size_t nStoredNodes() const;

 private:
  /// Generates the row of the key with the given index of a request.
  using Generator = std::function<RowPtr(size_t)>;

  /**
   * @brief Returns the rows of @p keys: those in use, those being generated by another request
   * (after waiting for them), and the missing ones, generated with @p generate(i) (in parallel if
   * they have at least @c constants::sparse_grid_storage::MIN_NODES_FOR_CONCURRENCY nodes; the
   * expected sizes come from @p expectedSize(i)).
   */
  std::vector<RowPtr> resolve(std::span<const NodeRowKey> keys, const Generator& generate,
                              const std::function<size_t(size_t)>& expectedSize);

  /**
   * @brief With the lock held: takes the rows of @p keys that are in use into @p result, the
   * futures of those being generated into @p waits, and registers the others as being generated
   * by this request (their indices in @p mine, a promise each in @p promises).
   */
  void claim(std::span<const NodeRowKey> keys, std::vector<RowPtr>& result,
             std::vector<std::shared_future<RowPtr>>& waits, std::vector<size_t>& mine,
             std::vector<std::promise<RowPtr>>& promises);

  /// @brief Enters the rows generated for @p keys at @p mine (null: failed) as generated.
  void publish(std::span<const NodeRowKey> keys, const std::vector<size_t>& mine,
               const std::vector<RowPtr>& rows);

  /// @brief Removes the entries of rows no longer in use (with the lock held).
  void pruneIfLarge();

  mutable std::mutex mutex_;  ///< Guards the maps.
  std::unordered_map<NodeRowKey, std::weak_ptr<const base::DataVector>> rows_;  ///< Generated.
  std::unordered_map<NodeRowKey, std::shared_future<RowPtr>> pending_;  ///< Being generated.
  size_t pruneAt_;  ///< Size of @c rows_ at which expired entries are removed.
};

}  // namespace combigrid
}  // namespace sgpp
